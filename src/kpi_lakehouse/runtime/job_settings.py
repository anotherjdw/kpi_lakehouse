"""The run record every ETL job in this project emits: one line of JSON per run.

Generated by `engineering-automation scaffold create-project`. Edit the scaffold template,
not this file.

Each job's `run()` parses its arguments and resolves its processing dates, then opens
`job_run()`, which emits exactly one record when the run ends, whether it succeeded, failed
or was stopped, and wraps each of read, transform and write in `phase()`. A run that fails
or is stopped also publishes one alert to the project's SNS topic.

Two deliberate omissions, decided rather than overlooked:
    * No `GlueContext` / `DynamicFrame`. Every read and write in this package
      uses the plain Spark SQL API, so the Glue wrapper layer buys nothing.
    * No `Job.init()` / `Job.commit()`. Those exist to drive Glue job
      bookmarks. The processing dates are resolved explicitly from the job's
      arguments, so bookmarks would duplicate -- and eventually contradict --
      that logic. The absence of `job.commit()` is intentional.
"""

import argparse
import json
import signal
import time
import traceback
from argparse import Namespace
from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime
from types import FrameType
from typing import Any, Protocol, cast
from urllib.parse import quote

RUN_RECORD_PREFIX = "RUN_RECORD"
ALERT_PUBLISH_FAILED_PREFIX = "ALERT_PUBLISH_FAILED"
DATA_PRODUCT = "kpi_lakehouse"

# SNS refuses a subject longer than this.
SUBJECT_MAX_LENGTH = 100


class JobStopped(BaseException):
    """The driver received SIGTERM: the run was stopped by hand or reached its Glue timeout.

    A `BaseException`, like `KeyboardInterrupt`, so an `except Exception` in a job's own
    code can't swallow the stop.
    """


class SnsClient(Protocol):
    """The one SNS call `job_run` makes, typed here since boto3's SNS stubs aren't installed."""

    def publish(self, *, TopicArn: str, Subject: str, Message: str) -> Any:
        """Publish one message to a topic."""


@dataclass
class RunRecord:
    """One structured summary of a single job execution.

    Mutable by design: `job_run` fills in the outcome fields, `phase` tracks
    which stage is executing, and the job body may attach anything else to
    `metrics`.
    """

    job_name: str
    started_at: str
    processing_dates: dict[str, list[str]]
    status: str = "RUNNING"
    phase: str | None = None
    glue_job_name: str | None = None
    glue_run_id: str | None = None
    environment: str | None = None
    finished_at: str | None = None
    duration_seconds: float | None = None
    phase_durations: dict[str, float] = field(default_factory=dict)
    error_type: str | None = None
    error_message: str | None = None
    traceback: str | None = None
    metrics: dict[str, Any] = field(default_factory=dict)


@contextmanager
def phase(record: RunRecord, name: str) -> Iterator[None]:
    """Mark which stage of the job is executing, and time it.

    Nothing resets `record.phase` on the way out of a failure, so it still
    names the stage that was running when the exception escaped. `job_run`
    clears it on success, so a non-null phase on an emitted record always
    means "this is where it broke".
    """
    record.phase = name
    started = time.monotonic()
    try:
        yield
    finally:
        record.phase_durations[name] = round(time.monotonic() - started, 3)


@contextmanager
def job_run(
    job_name: str, args: Namespace, processing_dates: dict[str, list[str]]
) -> Iterator[RunRecord]:
    """Wrap one run of a job so that exactly one run record is emitted, and failures alerted.

    The job parses its arguments and resolves its processing dates before it opens
    this, so a bad date argument fails the run without a record; Glue still marks the
    run failed and logs the error. Read, transform and write all run inside it.

    On failure the record is completed with the error and emitted, then the
    exception is re-raised unchanged -- swallowing it would leave Glue
    reporting SUCCEEDED for a run that produced nothing.

    SIGTERM, which Glue sends when a run is stopped by hand or reaches its timeout, is
    turned into a `JobStopped` error inside the run, so the record is emitted with the
    status `STOPPED` and the error is re-raised the same way. SIGTERM is ignored while
    the record is emitted and the alert published, so a second one can't cut them short.

    A run that ends `FAILED` or `STOPPED` publishes one alert to the topic named by the
    `--ALERT_TOPIC_ARN` argument, after the record is emitted. Without that argument (local
    runs and tests) nothing is published. A failed publish is printed on its own line and
    never replaces the job's error.

    Args:
        job_name: The job's name, i.e. its module name under `jobs/`. This is not
            the Glue resource name, which carries the `<product>-<env>` prefix and
            arrives separately as `--JOB_NAME`; both are recorded.
        args: The job's parsed arguments; their `JOB_NAME`, `JOB_RUN_ID` and
            `environment` are recorded.
        processing_dates: The dates the run reads for each partitioned source, keyed by
            its alias, as YYYY-MM-DD strings.

    Yields:
        The mutable `RunRecord` for this run.
    """
    record = RunRecord(
        job_name=job_name,
        started_at=_utc_now_iso(),
        processing_dates=processing_dates,
        glue_job_name=args.JOB_NAME,
        glue_run_id=args.JOB_RUN_ID,
        environment=args.environment,
    )
    topic_arn = alert_topic_arn()
    previous_handler = signal.signal(signal.SIGTERM, _raise_job_stopped)
    started = time.monotonic()
    try:
        yield record
    except BaseException as exc:
        record.status = "STOPPED" if isinstance(exc, JobStopped) else "FAILED"
        record.error_type = type(exc).__name__
        record.error_message = str(exc)[:2000]
        record.traceback = traceback.format_exc()[-4000:]
        raise
    else:
        record.status = "SUCCEEDED"
        record.phase = None
    finally:
        signal.signal(signal.SIGTERM, signal.SIG_IGN)
        try:
            record.finished_at = _utc_now_iso()
            record.duration_seconds = round(time.monotonic() - started, 3)
            emit_run_record(record)
            if topic_arn and record.status != "SUCCEEDED":
                publish_alert(record, topic_arn)
        finally:
            signal.signal(
                signal.SIGTERM,
                signal.SIG_DFL if previous_handler is None else previous_handler,
            )


def emit_run_record(record: RunRecord) -> None:
    """Write the run record to stdout as a single line of JSON.

    stdout is the whole transport. The Glue jobs set
    `--enable-continuous-cloudwatch-log`, so the driver's stdout streams to
    CloudWatch Logs with no extra wiring, no IAM beyond what the job already
    has, and nothing to fail independently of the job itself.

    The constant prefix makes the record addressable by a CloudWatch metric
    filter or a Logs Insights query without having to parse it out of the
    surrounding Spark noise.

    This record is for humans and observability only. Orchestration keys off
    Glue's own job-run state, which is set by the script's exit code -- which
    is why `job_run` re-raises rather than reporting failure only here.
    """
    payload = json.dumps(asdict(record), default=str, sort_keys=True)
    print(f"{RUN_RECORD_PREFIX} {payload}", flush=True)


def alert_topic_arn(argv: list[str] | None = None) -> str | None:
    """Read the alert topic's ARN from the `--ALERT_TOPIC_ARN` Glue argument.

    Read here, with its own parser, so no job's `parse_arguments` has to declare it. Every
    other argument is ignored.

    Args:
        argv: The arguments to read; the process's own when None.

    Returns:
        The topic ARN, or None when the argument isn't given, as in local runs and tests.
    """
    parser = argparse.ArgumentParser(add_help=False, allow_abbrev=False)
    parser.add_argument("--ALERT_TOPIC_ARN", type=str)
    arn: str | None = parser.parse_known_args(argv)[0].ALERT_TOPIC_ARN
    return arn or None


def publish_alert(record: RunRecord, topic_arn: str) -> None:
    """Publish one alert for a failed or stopped run, never raising.

    A publish that fails is printed on its own line, prefixed `ALERT_PUBLISH_FAILED`, and
    the job's own error is still re-raised by `job_run`.

    Args:
        record: The completed run record of the failed or stopped run.
        topic_arn: The ARN of the topic to publish to; the SNS client's region is taken
            from it.
    """
    try:
        region = topic_arn.split(":")[3]
        sns_client(region).publish(
            TopicArn=topic_arn,
            Subject=alert_subject(record),
            Message=alert_message(record, region),
        )
    except Exception as exc:
        print(f"{ALERT_PUBLISH_FAILED_PREFIX} {type(exc).__name__}: {exc}", flush=True)


def sns_client(region: str) -> SnsClient:
    """Create the SNS client the alert is published with.

    Short connect and read timeouts and a single attempt, so a publish can't hold the run
    open for long after Glue has asked it to stop.

    Args:
        region: The AWS region of the topic.

    Returns:
        A boto3 SNS client for that region.
    """
    import boto3
    from botocore.config import Config

    config = Config(
        connect_timeout=5, read_timeout=5, retries={"mode": "standard", "max_attempts": 1}
    )
    return cast(SnsClient, boto3.client("sns", region_name=region, config=config))


def alert_subject(record: RunRecord) -> str:
    """Build the alert's subject: product, environment, job, status and the step it ended in.

    Args:
        record: The completed run record.

    Returns:
        `[<data_product> <environment>] <job_name> <status> in <phase>`, without the
        `in <phase>` part when no step had started, cut to SNS's 100-character limit.
    """
    subject = f"[{DATA_PRODUCT} {record.environment}] {record.job_name} {record.status}"
    if record.phase:
        subject += f" in {record.phase}"
    return subject[:SUBJECT_MAX_LENGTH]


def alert_message(record: RunRecord, region: str) -> str:
    """Build the alert's body from the run record; the traceback stays in the logs.

    Args:
        record: The completed run record.
        region: The AWS region the job runs in, for the link to the run.

    Returns:
        Plain text: what happened, the error, the processing dates, the Glue job name and
        run id, and a link to the run in the Glue console.
    """
    what = "was stopped by hand or at its timeout" if record.status == "STOPPED" else "failed"
    where = f" in {record.phase}" if record.phase else ""
    lines = [
        f"{record.job_name} ({DATA_PRODUCT}, {record.environment}) {what}{where}.",
        "",
        f"Error: {record.error_type}: {record.error_message}",
        "",
        "Processing dates:",
        *(
            f"  {alias}: {_date_span(dates)}"
            for alias, dates in sorted(record.processing_dates.items())
        ),
        "",
        f"Glue job: {record.glue_job_name}",
        f"Run id: {record.glue_run_id}",
        f"Started: {record.started_at}",
        f"Finished: {record.finished_at}",
        f"Run: {_run_url(region, record.glue_job_name, record.glue_run_id)}",
    ]
    return "\n".join(lines)


def _raise_job_stopped(signum: int, frame: FrameType | None) -> None:
    raise JobStopped("SIGTERM received: the run was stopped by hand or at its timeout")


def _date_span(dates: list[str]) -> str:
    if not dates:
        return "none"
    if len(dates) == 1:
        return dates[0]
    return f"{dates[0]} to {dates[-1]} ({len(dates)} dates)"


def _run_url(region: str, glue_job_name: str | None, glue_run_id: str | None) -> str:
    return (
        f"https://{region}.console.aws.amazon.com/gluestudio/home?region={region}"
        f"#/job/{quote(glue_job_name or '')}/run/{quote(glue_run_id or '')}"
    )


def _utc_now_iso() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")
