"""The run record every ETL job in this project emits: one line of JSON per run.

Generated by `engineering-automation scaffold create-project`. Edit the scaffold template,
not this file.

Each job's `run()` parses its arguments and resolves its processing dates, then opens
`job_run()`, which emits exactly one record per run, whether it succeeded, failed, was
stopped or timed out, and wraps each of read, transform and write in `phase()`. A run that
doesn't succeed also publishes one alert to the project's SNS topic.

Two deliberate omissions, decided rather than overlooked:
    * No `GlueContext` / `DynamicFrame`. Every read and write in this package
      uses the plain Spark SQL API, so the Glue wrapper layer buys nothing.
    * No `Job.init()` / `Job.commit()`. Those exist to drive Glue job
      bookmarks. The processing dates are resolved explicitly from the job's
      arguments, so bookmarks would duplicate -- and eventually contradict --
      that logic. The absence of `job.commit()` is intentional.
"""

import argparse
import json
import threading
import time
import traceback
from argparse import Namespace
from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime, timedelta
from typing import Any, Protocol, cast
from urllib.parse import quote

RUN_RECORD_PREFIX = "RUN_RECORD"
ALERT_PUBLISH_FAILED_PREFIX = "ALERT_PUBLISH_FAILED"
RUN_WATCH_FAILED_PREFIX = "RUN_WATCH_FAILED"
DATA_PRODUCT = "kpi_lakehouse"

# SNS refuses a subject longer than this.
SUBJECT_MAX_LENGTH = 100

# How often the watcher reads the run's state, and how long before the run's Glue timeout it
# reports the timeout. Glue ends a stopped or timed-out run without a signal the job can catch.
WATCH_INTERVAL_SECONDS = 15.0
TIMEOUT_MARGIN_SECONDS = 60.0

# Glue's states for a run being stopped, or stopped.
STOP_STATES = ("STOPPING", "STOPPED")


class SnsClient(Protocol):
    """The one SNS call `job_run` makes, typed here since boto3's SNS stubs aren't installed."""

    def publish(self, *, TopicArn: str, Subject: str, Message: str) -> Any:
        """Publish one message to a topic."""


class GlueClient(Protocol):
    """The one Glue call the watcher makes, typed here since boto3's Glue stubs aren't installed."""

    def get_job_run(self, *, JobName: str, RunId: str) -> Any:
        """Read one job run."""


@dataclass
class RunRecord:
    """One structured summary of a single job execution.

    Mutable by design: `job_run` fills in the outcome fields, `phase` tracks
    which stage is executing, and the job body may attach anything else to
    `metrics`.
    """

    job_name: str
    started_at: str
    processing_dates: dict[str, list[str]]
    status: str = "RUNNING"
    phase: str | None = None
    glue_job_name: str | None = None
    glue_run_id: str | None = None
    environment: str | None = None
    finished_at: str | None = None
    duration_seconds: float | None = None
    phase_durations: dict[str, float] = field(default_factory=dict)
    error_type: str | None = None
    error_message: str | None = None
    traceback: str | None = None
    metrics: dict[str, Any] = field(default_factory=dict)


class _RecordOnce:
    """Ends a run's record exactly once, from the main thread or the watcher, whichever is first.

    The first caller sets the outcome, emits the record and publishes the alert; any later
    call does nothing, so a run that carries on after the watcher reported it prints no second
    record.
    """

    def __init__(self, record: RunRecord, topic_arn: str | None, started: float) -> None:
        self.record = record
        self.topic_arn = topic_arn
        self.started = started
        self.done = False
        self._lock = threading.Lock()

    def finish(
        self,
        status: str,
        error_type: str | None = None,
        error_message: str | None = None,
        trace: str | None = None,
    ) -> bool:
        """Complete, emit and, unless it succeeded, publish the record, if not done already.

        Args:
            status: SUCCEEDED, FAILED, STOPPED or TIMEOUT.
            error_type: The error's type, or what ended the run, when it didn't succeed.
            error_message: The error's message, or why the run ended.
            trace: The traceback of the error, when there was one.

        Returns:
            True if this call ended the record, False if it had already been ended.
        """
        with self._lock:
            if self.done:
                return False
            self.done = True
            record = self.record
            record.status = status
            if status == "SUCCEEDED":
                record.phase = None
            record.error_type = error_type
            record.error_message = error_message
            record.traceback = trace
            record.finished_at = _utc_now_iso()
            record.duration_seconds = round(time.monotonic() - self.started, 3)
            emit_run_record(record)
            if self.topic_arn and status != "SUCCEEDED":
                publish_alert(record, self.topic_arn)
            return True


@contextmanager
def phase(record: RunRecord, name: str) -> Iterator[None]:
    """Mark which stage of the job is executing, and time it.

    Nothing resets `record.phase` on the way out of a failure, so it still
    names the stage that was running when the exception escaped. `job_run`
    clears it on success, so a non-null phase on an emitted record always
    means "this is where it broke".
    """
    record.phase = name
    started = time.monotonic()
    try:
        yield
    finally:
        record.phase_durations[name] = round(time.monotonic() - started, 3)


@contextmanager
def job_run(
    job_name: str, args: Namespace, processing_dates: dict[str, list[str]]
) -> Iterator[RunRecord]:
    """Wrap one run of a job so that exactly one run record is emitted, and alerts are sent.

    The job parses its arguments and resolves its processing dates before it opens
    this, so a bad date argument fails the run without a record; Glue still marks the
    run failed and logs the error. Read, transform and write all run inside it.

    On failure the record is completed with the error and emitted, then the
    exception is re-raised unchanged -- swallowing it would leave Glue
    reporting SUCCEEDED for a run that produced nothing.

    Glue ends a stopped or timed-out run without a signal the job can catch, so while the
    run is open a watcher thread reads the run's own state from Glue. When the run is being
    stopped, or less than a minute is left before its timeout, the watcher emits the record
    as `STOPPED` or `TIMEOUT`, with the step the run was in, and publishes the alert. That
    record is the run's only one: if the run carries on and ends, nothing more is emitted.

    A run that doesn't succeed publishes one alert to the topic named by the
    `--ALERT_TOPIC_ARN` argument, after the record is emitted. Without that argument (local
    runs and tests) nothing is published and no watcher starts. A failed publish is printed
    on its own line and never replaces the job's error.

    Args:
        job_name: The job's name, i.e. its module name under `jobs/`. This is not
            the Glue resource name, which carries the `<product>-<env>` prefix and
            arrives separately as `--JOB_NAME`; both are recorded.
        args: The job's parsed arguments; their `JOB_NAME`, `JOB_RUN_ID` and
            `environment` are recorded.
        processing_dates: The dates the run reads for each partitioned source, keyed by
            its alias, as YYYY-MM-DD strings.

    Yields:
        The mutable `RunRecord` for this run.
    """
    record = RunRecord(
        job_name=job_name,
        started_at=_utc_now_iso(),
        processing_dates=processing_dates,
        glue_job_name=args.JOB_NAME,
        glue_run_id=args.JOB_RUN_ID,
        environment=args.environment,
    )
    topic_arn = alert_topic_arn()
    ending = _RecordOnce(record, topic_arn, time.monotonic())
    stop_watching = threading.Event()
    if topic_arn and record.glue_job_name and record.glue_run_id:
        threading.Thread(
            target=watch_run,
            args=(ending, record.glue_job_name, record.glue_run_id, topic_arn, stop_watching),
            name="run-watcher",
            daemon=True,
        ).start()
    try:
        yield record
    except BaseException as exc:
        ending.finish(
            "FAILED",
            error_type=type(exc).__name__,
            error_message=str(exc)[:2000],
            trace=traceback.format_exc()[-4000:],
        )
        raise
    else:
        ending.finish("SUCCEEDED")
    finally:
        stop_watching.set()


def watch_run(
    ending: _RecordOnce,
    glue_job_name: str,
    run_id: str,
    topic_arn: str,
    stop_watching: threading.Event,
) -> None:
    """Report the run as STOPPED or TIMEOUT from its own Glue state, until the run ends.

    Reads the run every `WATCH_INTERVAL_SECONDS`. A read that fails is printed, prefixed
    `RUN_WATCH_FAILED`, and tried again at the next interval; it never fails the run.

    Args:
        ending: Ends the run's record once, shared with `job_run`.
        glue_job_name: The Glue job's name.
        run_id: The Glue run's id.
        topic_arn: The alert topic; the Glue client's region is taken from it.
        stop_watching: Set by `job_run` when the run ends.
    """
    client: GlueClient | None = None
    while not stop_watching.wait(WATCH_INTERVAL_SECONDS):
        try:
            if client is None:
                client = glue_client(topic_arn.split(":")[3])
            run = client.get_job_run(JobName=glue_job_name, RunId=run_id)["JobRun"]
            outcome = run_outcome(run, datetime.now(UTC))
        except Exception as exc:
            print(f"{RUN_WATCH_FAILED_PREFIX} {type(exc).__name__}: {exc}", flush=True)
            continue
        if outcome is not None:
            status, reason = outcome
            ending.finish(status, error_type=status, error_message=reason)
            return


def run_outcome(run: dict[str, Any], now: datetime) -> tuple[str, str] | None:
    """Decide from a run's Glue state whether it is being stopped or is about to time out.

    Args:
        run: The `JobRun` from Glue's `GetJobRun`: its `JobRunState`, `StartedOn` and
            `Timeout` (minutes) are read.
        now: The current time, timezone-aware.

    Returns:
        `("STOPPED", reason)`, `("TIMEOUT", reason)`, or None while the run carries on.
    """
    if run.get("JobRunState") in STOP_STATES:
        return "STOPPED", "The run was stopped by hand."
    started, timeout = run.get("StartedOn"), run.get("Timeout")
    if started is not None and timeout:
        ends_at = started + timedelta(minutes=timeout)
        if now >= ends_at - timedelta(seconds=TIMEOUT_MARGIN_SECONDS):
            return "TIMEOUT", (
                f"The run reaches its {timeout}-minute timeout at "
                f"{ends_at.isoformat(timespec='seconds')}, where Glue ends it."
            )
    return None


def emit_run_record(record: RunRecord) -> None:
    """Write the run record to stdout as a single line of JSON.

    stdout is the whole transport. The Glue jobs set
    `--enable-continuous-cloudwatch-log`, so the driver's stdout streams to
    CloudWatch Logs with no extra wiring, no IAM beyond what the job already
    has, and nothing to fail independently of the job itself.

    The constant prefix makes the record addressable by a CloudWatch metric
    filter or a Logs Insights query without having to parse it out of the
    surrounding Spark noise.

    This record is for humans and observability only. Orchestration keys off
    Glue's own job-run state, which is set by the script's exit code -- which
    is why `job_run` re-raises rather than reporting failure only here.
    """
    payload = json.dumps(asdict(record), default=str, sort_keys=True)
    print(f"{RUN_RECORD_PREFIX} {payload}", flush=True)


def alert_topic_arn(argv: list[str] | None = None) -> str | None:
    """Read the alert topic's ARN from the `--ALERT_TOPIC_ARN` Glue argument.

    Read here, with its own parser, so no job's `parse_arguments` has to declare it. Every
    other argument is ignored.

    Args:
        argv: The arguments to read; the process's own when None.

    Returns:
        The topic ARN, or None when the argument isn't given, as in local runs and tests.
    """
    parser = argparse.ArgumentParser(add_help=False, allow_abbrev=False)
    parser.add_argument("--ALERT_TOPIC_ARN", type=str)
    arn: str | None = parser.parse_known_args(argv)[0].ALERT_TOPIC_ARN
    return arn or None


def publish_alert(record: RunRecord, topic_arn: str) -> None:
    """Publish one alert for a run that didn't succeed, never raising.

    A publish that fails is printed on its own line, prefixed `ALERT_PUBLISH_FAILED`, and
    the job's own error is still re-raised by `job_run`.

    Args:
        record: The completed run record of the failed, stopped or timed-out run.
        topic_arn: The ARN of the topic to publish to; the SNS client's region is taken
            from it.
    """
    try:
        region = topic_arn.split(":")[3]
        sns_client(region).publish(
            TopicArn=topic_arn,
            Subject=alert_subject(record),
            Message=alert_message(record, region),
        )
    except Exception as exc:
        print(f"{ALERT_PUBLISH_FAILED_PREFIX} {type(exc).__name__}: {exc}", flush=True)


def _client_config() -> Any:
    """Short connect and read timeouts and a single attempt, so no AWS call holds a run open."""
    from botocore.config import Config

    return Config(
        connect_timeout=5, read_timeout=5, retries={"mode": "standard", "max_attempts": 1}
    )


def sns_client(region: str) -> SnsClient:
    """Create the SNS client the alert is published with.

    Args:
        region: The AWS region of the topic.

    Returns:
        A boto3 SNS client for that region.
    """
    import boto3

    return cast(SnsClient, boto3.client("sns", region_name=region, config=_client_config()))


def glue_client(region: str) -> GlueClient:
    """Create the Glue client the watcher reads the run's state with.

    Args:
        region: The AWS region the job runs in.

    Returns:
        A boto3 Glue client for that region.
    """
    import boto3

    return cast(GlueClient, boto3.client("glue", region_name=region, config=_client_config()))


def alert_subject(record: RunRecord) -> str:
    """Build the alert's subject: product, environment, job, status and the step it ended in.

    Args:
        record: The completed run record.

    Returns:
        `[<data_product> <environment>] <job_name> <status> in <phase>`, without the
        `in <phase>` part when no step had started, cut to SNS's 100-character limit.
    """
    subject = f"[{DATA_PRODUCT} {record.environment}] {record.job_name} {record.status}"
    if record.phase:
        subject += f" in {record.phase}"
    return subject[:SUBJECT_MAX_LENGTH]


def alert_message(record: RunRecord, region: str) -> str:
    """Build the alert's body from the run record; the traceback stays in the logs.

    Args:
        record: The completed run record.
        region: The AWS region the job runs in, for the link to the run.

    Returns:
        Plain text: what happened, the error or reason, the processing dates, the Glue job
        name and run id, and a link to the run in the Glue console.
    """
    what = {
        "STOPPED": "was stopped",
        "TIMEOUT": "is timing out",
    }.get(record.status, "failed")
    where = f" in {record.phase}" if record.phase else ""
    if record.status in ("STOPPED", "TIMEOUT"):
        detail = f"Reason: {record.error_message}"
    else:
        detail = f"Error: {record.error_type}: {record.error_message}"
    lines = [
        f"{record.job_name} ({DATA_PRODUCT}, {record.environment}) {what}{where}.",
        "",
        detail,
        "",
        "Processing dates:",
        *(
            f"  {alias}: {_date_span(dates)}"
            for alias, dates in sorted(record.processing_dates.items())
        ),
        "",
        f"Glue job: {record.glue_job_name}",
        f"Run id: {record.glue_run_id}",
        f"Started: {record.started_at}",
        f"Recorded: {record.finished_at}",
        f"Run: {_run_url(region, record.glue_job_name, record.glue_run_id)}",
    ]
    return "\n".join(lines)


def _date_span(dates: list[str]) -> str:
    if not dates:
        return "none"
    if len(dates) == 1:
        return dates[0]
    return f"{dates[0]} to {dates[-1]} ({len(dates)} dates)"


def _run_url(region: str, glue_job_name: str | None, glue_run_id: str | None) -> str:
    return (
        f"https://{region}.console.aws.amazon.com/gluestudio/home?region={region}"
        f"#/job/{quote(glue_job_name or '')}/run/{quote(glue_run_id or '')}"
    )


def _utc_now_iso() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")
